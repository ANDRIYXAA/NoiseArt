// ============================================================================
// NoiseArt — Точка входу (Entry Point)
// ============================================================================
// Це найперший файл, який виконується при запуску програми.
// Він створює об'єкт App і запускає головний цикл.
//
// Чому так мало коду? Бо вся логіка живе в класі App.
// main() лише створює App і запускає його — це хороша практика,
// яка називається "Single Responsibility Principle" (принцип єдиної
// відповідальності): кожен елемент відповідає за одну річ.
// ============================================================================

#include "App/App.h"  // Наш клас App
#include <SDL3/SDL_main.h>

#ifdef _WIN32
#include <windows.h>
#endif

// argc (argument count) — кількість аргументів командного рядка
// argv (argument values) — масив рядків з аргументами
// Наприклад, якщо запустити "NoiseArt.exe photo.png",
// то argc = 2, argv[0] = "NoiseArt.exe", argv[1] = "photo.png"
int main(int argc, char* argv[])
{
#ifdef _WIN32
    // Налаштовуємо консоль на UTF-8 для коректного відображення української мови
    SetConsoleOutputCP(CP_UTF8);
#endif

    // Створюємо єдиний об'єкт застосунку
    NoiseArt::App app;

    // Ініціалізація: SDL2, OpenGL, ImGui
    // Якщо щось пішло не так — виходимо з кодом помилки (1)
    if (!app.init()) {
        return 1;
    }

    // Головний цикл — працює доки користувач не закриє вікно
    app.run();

    // Очищення ресурсів (пам'ять, контексти, вікна)
    app.shutdown();

    // Код 0 = програма завершилась успішно
    return 0;
}
